#!/usr/bin/env ruby
# =============================================================================
# scripts/devops/workflow_reference.rb — generate docs/reference/workflows.md
# -----------------------------------------------------------------------------
# The workflow inventory — every .github/workflows/*.yml with its triggers, its
# *_ENABLED kill switch, the repository variables and secrets it reads, and the
# one-line summary from its header comment — used to be hand-copied into
# docs/CICD.md, where it covered 11 of 30 workflows and drifted. It is derived
# from the workflow files instead (fleet docs framework, UPS-DOC-05):
# docs/CICD.md keeps the narrative, this file keeps the list.
#
#   ruby scripts/devops/workflow_reference.rb --write   # rewrite the reference
#   ruby scripts/devops/workflow_reference.rb --check   # exit 1 when it is stale
#
# check_drift.rb calls WorkflowReference.stale, so a stale reference is a
# harness finding blamed on the workflow that changed — which PR scoping then
# lands on the PR that changed it. Stdlib only.
# =============================================================================
require 'yaml'
require_relative '../ci/_lib'

module WorkflowReference
  module_function

  WF_DIR = File.join(LH::ROOT, '.github', 'workflows')
  OUT    = 'docs/reference/workflows.md'
  CMD    = 'ruby scripts/devops/workflow_reference.rb --write'

  # --- facts, from the workflow files ----------------------------------------

  def workflows
    Dir[File.join(WF_DIR, '*.{yml,yaml}')].sort.map { |p| facts(p) }
  end

  def facts(path)
    text = LH.read(path)
    file = File.basename(path)
    doc  = (YAML.safe_load(text, aliases: true) rescue nil)
    doc  = {} unless doc.is_a?(Hash)
    # Psych reads the bare key `on:` as YAML 1.1 boolean true.
    on   = doc.key?('on') ? doc['on'] : doc[true]
    code = text.lines.reject { |l| l =~ /\A\s*#/ }.join # a commented-out line reads nothing
    vars = code.scan(/\bvars\.([A-Za-z_][A-Za-z0-9_]*)/).flatten.uniq.sort
    secrets = code.scan(/\bsecrets\.([A-Za-z_][A-Za-z0-9_]*)/).flatten.uniq.sort - ['GITHUB_TOKEN']
    house, summary = header_summary(text, file)
    { file: file, name: doc['name'].to_s, triggers: triggers(on), vars: vars,
      switches: vars.select { |v| v.end_with?('_ENABLED') }, secrets: secrets,
      summary: summary, house: house }
  end

  def triggers(on)
    case on
    when String then [event_label(on, nil)]
    when Array  then on.map { |e| event_label(e.to_s, nil) }
    when Hash
      on.flat_map do |event, cfg|
        next Array(cfg).map { |s| "cron `#{s.is_a?(Hash) ? s['cron'] : s}`" } if event.to_s == 'schedule'
        [event_label(event.to_s, cfg)]
      end
    else []
    end
  end

  def event_label(event, cfg)
    case event
    when 'workflow_dispatch' then 'manual'
    when 'workflow_call'     then 'reusable'
    when 'workflow_run'
      names = cfg.is_a?(Hash) ? Array(cfg['workflows']) : []
      names.empty? ? '`workflow_run`' : "after #{names.map { |n| "`#{n}`" }.join(', ')}"
    else "`#{event}`"
    end
  end

  # The repo's own workflows open with `# <file> — <summary>` (house = true).
  # Hub-seeded and generated ones do not; their summary is the first sentence
  # of their header comment, and a stale row of theirs is only a warning,
  # because the fan-out PR that changes them cannot run this generator.
  def header_summary(text, file)
    lines = []
    text.each_line do |raw|
      l = raw.strip
      next if l.empty? || l.start_with?('name:')
      break unless l.start_with?('#')
      lines << l.sub(/\A#+\s?/, '').rstrip
    end
    lines.each do |l|
      return [true, l.split(/\s+—\s+/, 2).last.strip] if l =~ /\A(?:\S*\/)?#{Regexp.escape(file)}\s+—\s+\S/
    end
    blueprint = lines.map { |l| l[/\Ablueprint:\s*(\S+)/, 1] }.compact.first
    return [false, "Generated by GitFactory from `#{blueprint}`."] if blueprint
    para = []
    lines.each do |l|
      next if l =~ /\A[=\-]{5,}\z/ || l =~ /GENERATED/
      if l =~ /\Akit:/
        tail = l.split(/\s+—\s+/, 2)[1]
        para << tail if tail
        next
      end
      break if l.empty? && !para.empty?
      para << l unless l.empty?
    end
    sentence = para.join(' ')[/\A(.+?[.!?])(?:\s|\z)/, 1] || para.join(' ')
    [false, sentence.strip]
  end

  # --- rendering ---------------------------------------------------------------

  def cell(text)
    text.to_s.empty? ? '—' : text.to_s.gsub('|', '\\|')
  end

  def code_list(items)
    items.empty? ? '—' : items.map { |i| "`#{i}`" }.join(', ')
  end

  def render(wfs = workflows)
    out = +"<!-- GENERATED by #{CMD} — do not edit by hand -->\n"
    out << "# Workflow reference\n\n"
    out << "> Every GitHub Actions workflow in `.github/workflows/` — its triggers, kill switch, " \
           "repository variables and secrets — generated from the workflow files themselves.\n\n"
    out << "How the workflows fit together (the tiers, the one required check, the autonomy posture) " \
           "is explained in [CICD.md](../CICD.md). A **switch** is a `*_ENABLED` repository variable " \
           "the workflow reads before it acts; turning one on is a guardrail change " \
           "([CICD.md](../CICD.md#turning-on-continuous-autonomy-deliberate)).\n\n"
    out << "## Workflows\n\n"
    out << "| Workflow | Name | Triggers | Switch | Summary |\n| --- | --- | --- | --- | --- |\n"
    wfs.each do |w|
      out << "| [`#{w[:file]}`](../../.github/workflows/#{w[:file]}) | #{cell(w[:name])} | " \
             "#{cell(w[:triggers].join(' · '))} | #{code_list(w[:switches])} | #{cell(w[:summary])} |\n"
    end
    [['Repository variables', 'Variable', :vars], ['Secrets', 'Secret', :secrets]].each do |title, col, key|
      readers = Hash.new { |h, k| h[k] = [] }
      wfs.each { |w| w[key].each { |name| readers[name] << w[:file] } }
      out << "\n## #{title}\n\n| #{col} | Read by |\n| --- | --- |\n"
      readers.keys.sort.each { |name| out << "| `#{name}` | #{code_list(readers[name])} |\n" }
    end
    out
  end

  # --- staleness, blamed per workflow -------------------------------------------

  # file => { row:, vars:, secrets: } parsed back out of a rendered reference, so
  # the committed file and a fresh render are compared workflow by workflow.
  def index(text)
    sig = Hash.new { |h, k| h[k] = { row: nil, vars: [], secrets: [] } }
    section = nil
    text.to_s.each_line do |l|
      if (m = l.match(/\A## (.+?)\s*\z/))
        section = m[1]
      elsif section == 'Workflows' && (m = l.match(/\A\| \[`([^`]+)`\]/))
        sig[m[1]][:row] = l.rstrip
      elsif (m = l.match(/\A\| `([^`]+)` \| (.+) \|\s*\z/))
        key = section == 'Secrets' ? :secrets : :vars
        m[2].scan(/`([^`]+)`/).flatten.each { |f| sig[f][key] << m[1] }
      end
    end
    sig
  end

  def current
    path = File.join(LH::ROOT, OUT)
    File.exist?(path) ? LH.read(path) : nil
  end

  # [[path to blame, repo-owned?], ...] — empty when the reference is current.
  def stale(committed = current)
    wfs   = workflows
    fresh = render(wfs)
    return [] if committed == fresh
    return [[OUT, true]] if committed.nil?
    house = wfs.map { |w| [w[:file], w[:house]] }.to_h
    have, want = index(committed), index(fresh)
    blamed = (have.keys | want.keys).sort.reject { |f| have[f] == want[f] }
    return [[OUT, true]] if blamed.empty?
    blamed.map { |f| [".github/workflows/#{f}", house.fetch(f, true)] }
  end
end

if __FILE__ == $PROGRAM_NAME
  case ARGV[0]
  when '--write'
    path = File.join(LH::ROOT, WorkflowReference::OUT)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, WorkflowReference.render)
    puts "[workflow_reference] wrote #{WorkflowReference::OUT}"
  when '--check'
    blamed = WorkflowReference.stale
    if blamed.empty?
      puts "[workflow_reference] #{WorkflowReference::OUT} is current"
    else
      blamed.each { |f, _| warn "[workflow_reference] stale for #{f}" }
      warn "[workflow_reference] run: #{WorkflowReference::CMD}"
      exit 1
    end
  else
    warn 'usage: ruby scripts/devops/workflow_reference.rb --write | --check'
    exit 2
  end
end
